// initDevboxEnvironment sets up devbox, direnv, and uv in the .weg directory
func initDevboxEnvironment(wegPath, version, dbVersion string) error {
	// Create .envrc - use env which devbox's python plugin creates automatically
	envrc := `# Generated by weg. Do not edit manually.
eval "$(devbox generate direnv --print-envrc)"
`
	wroteEnvrc, err := writeIfMissing(filepath.Join(wegPath, ".envrc"), envrc)
	if err != nil {
		return fmt.Errorf("failed to create .envrc: %w", err)
	}

	// Write service configs BEFORE devbox init/add
	// devbox won't overwrite existing files in devbox.d/
	PrintVerbose("Writing service configurations...")
	if err := writeServiceConfigs(wegPath); err != nil {
		return fmt.Errorf("failed to write service configs: %w", err)
	}

	// Write devbox.json directly with socket-only configuration
	PrintVerbose("Creating devbox.json...")
	if err := writeDevboxJSON(wegPath, version, dbVersion); err != nil {
		return fmt.Errorf("failed to create devbox.json: %w", err)
	}

	// Install devbox packages (this will use our pre-written configs)
	PrintVerbose("Installing dependencies via devbox...")
	if err := runCmdInDir(wegPath, "devbox", "install"); err != nil {
		// devbox.json marks the environment as set up; drop it (and our
		// .envrc, so the retry still direnv-allows it) so a re-run retries.
		os.Remove(filepath.Join(wegPath, "devbox.json"))
		if wroteEnvrc {
			os.Remove(filepath.Join(wegPath, ".envrc"))
		}
		return fmt.Errorf("devbox install failed: %w", err)
	}

	// Allow direnv - only for an .envrc weg wrote; trusting someone else's
	// is the user's call.
	if wroteEnvrc {
		PrintVerbose("Allowing direnv...")
		if err := runCmdInDir(wegPath, "direnv", "allow"); err != nil {
			// Don't fail on direnv error - might not be installed
			PrintVerbose("direnv not available: %v", err)
		}
	}

	// Create pyproject.toml for uv
	pyproject := `[project]
name = "frappe-bench"
version = "0.1.0"
requires-python = ">=3.11"
`
	if _, err := writeIfMissing(filepath.Join(wegPath, "pyproject.toml"), pyproject); err != nil {
		return fmt.Errorf("failed to create pyproject.toml: %w", err)
	}

	// Note: devbox's python plugin automatically creates env
	// No need to create a separate venv

	return nil
}

// writeIfMissing writes content to path unless the file already exists, and
// reports whether it wrote it: 'weg sync' also sets up devbox in existing
// bench roots, where these are the user's files.
func writeIfMissing(path, content string) (bool, error) {
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0644)
	if os.IsExist(err) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	if _, err := f.WriteString(content); err != nil {
		f.Close()
		return false, err
	}
	return true, f.Close()
}

// writeServiceConfigs creates devbox.d/ configs for socket-only operation
// These must be written BEFORE devbox install, as devbox won't overwrite existing files
func writeServiceConfigs(wegPath string) error {
	// Ensure we have an absolute path for socket locations
	absWegPath, err := filepath.Abs(wegPath)
	if err != nil {
		return fmt.Errorf("failed to get absolute path: %w", err)
	}

	// Create devbox.d/mariadb directory
	mariadbDir := filepath.Join(wegPath, "devbox.d", "mariadb")
	if err := os.MkdirAll(mariadbDir, 0755); err != nil {
		return fmt.Errorf("failed to create mariadb config dir: %w", err)
	}

	// MariaDB config - disable TCP networking, use socket only
	// This prevents port conflicts with system mariadb on port 3306
	myCnf := `# Generated by weg - socket-only configuration
# This prevents port conflicts with system mariadb

[mariadbd]
skip-networking
log_error = mysql.log
`
	if err := os.WriteFile(filepath.Join(mariadbDir, "my.cnf"), []byte(myCnf), 0644); err != nil {
		return fmt.Errorf("failed to write my.cnf: %w", err)
	}
	// mariadbd reads $MYSQL_HOME/my.cnf (.devbox/virtenv/mariadb/run). The
	// plugin's init hook links it to the file above, but `devbox services
	// start` can launch mariadbd before any hook has run, binding :3306.
	mariadbRun := filepath.Join(wegPath, ".devbox", "virtenv", "mariadb", "run")
	if err := os.MkdirAll(mariadbRun, 0755); err != nil {
		return fmt.Errorf("failed to create mariadb run dir: %w", err)
	}
	if err := os.Symlink(filepath.Join(absWegPath, "devbox.d", "mariadb", "my.cnf"), filepath.Join(mariadbRun, "my.cnf")); err != nil && !os.IsExist(err) {
		return fmt.Errorf("failed to link my.cnf: %w", err)
	}

	// Create devbox.d/redis directory and virtenv/redis for socket
	redisDir := filepath.Join(wegPath, "devbox.d", "redis")
	if err := os.MkdirAll(redisDir, 0755); err != nil {
		return fmt.Errorf("failed to create redis config dir: %w", err)
	}

	// Create virtenv/redis directory for the socket file
	redisVirtenv := filepath.Join(wegPath, ".devbox", "virtenv", "redis")
	if err := os.MkdirAll(redisVirtenv, 0755); err != nil {
		return fmt.Errorf("failed to create redis virtenv dir: %w", err)
	}

	// Redis config - disable TCP, use socket only
	// This prevents port conflicts with system redis on port 6379
	// Use absolute path for socket since redis-server working dir is unpredictable
	redisSocketPath := filepath.Join(absWegPath, ".devbox", "virtenv", "redis", "redis.sock")
	redisConf := fmt.Sprintf(`# Generated by weg - socket-only configuration
# This prevents port conflicts with system redis

# Disable TCP listening (port 0 = disabled)
port 0

# Enable Unix socket with absolute path
unixsocket %s
unixsocketperm 770

# Keep state out of the bench root (redis runs from there); cache/queue only
dir %s
save ""
`, redisSocketPath, filepath.Join(absWegPath, ".devbox", "virtenv", "redis"))

	if err := os.WriteFile(filepath.Join(redisDir, "redis.conf"), []byte(redisConf), 0644); err != nil {
		return fmt.Errorf("failed to write redis.conf: %w", err)
	}

	return nil
}

// writeDevboxJSON creates devbox.json with packages and socket-only env vars
func writeDevboxJSON(wegPath, version, dbVersion string) error {
	// devbox's current format is a name -> version map; the old list form
	// makes every devbox command suggest `devbox update`. Later entries win,
	// so a version-specific python/node replaces the base one.
	packages := map[string]string{}
	for _, pkg := range getDevboxPackages(version) {
		name, ver, ok := strings.Cut(pkg, "@")
		if !ok {
			ver = "latest"
		}
		packages[name] = ver
	}
	if dbVersion != "" {
		packages["mariadb"] = dbVersion
	}

	// Build devbox.json structure
	config := map[string]any{
		"$schema":  "https://raw.githubusercontent.com/jetify-com/devbox/main/.schema/devbox.schema.json",
		"packages": packages,
		"env": map[string]string{
			// Disable Redis TCP port - forces socket-only operation
			// The redis process-compose uses: redis-server $REDIS_CONF --port $REDIS_PORT
			"REDIS_PORT": "0",
			// Pin the virtualenv to <project>/env so devbox-run shells see the
			// same venv as direnv users. devbox's python plugin creates it on first run.
			"VENV_DIR":     "$DEVBOX_PROJECT_ROOT/env",
			"UV_VENV_PATH": "$DEVBOX_PROJECT_ROOT/env",
			"VIRTUAL_ENV":  "$DEVBOX_PROJECT_ROOT/env",
		},
		"shell": map[string]any{
			"init_hook": []string{
				"echo 'Weg environment ready' > /dev/null",
			},
		},
	}

	data, err := json.MarshalIndent(config, "", "  ")
	if err != nil {
		return fmt.Errorf("failed to marshal devbox.json: %w", err)
	}

	if err := os.WriteFile(filepath.Join(wegPath, "devbox.json"), data, 0644); err != nil {
		return fmt.Errorf("failed to write devbox.json: %w", err)
	}

	return nil
}

// syncDevboxEnv merges weg.toml's [env] into devbox.json's env, so every
// devbox-run command and service sees it. Only rewrites on change.
func syncDevboxEnv(benchPath string, env map[string]string) error {
	if len(env) == 0 {
		return nil
	}
	path := filepath.Join(benchPath, "devbox.json")
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	var devbox map[string]any
	if err := json.Unmarshal(data, &devbox); err != nil {
		return fmt.Errorf("failed to parse devbox.json: %w", err)
	}
	current, _ := devbox["env"].(map[string]any)
	if current == nil {
		current = map[string]any{}
	}
	changed := false
	for k, v := range env {
		if current[k] != v {
			current[k] = v
			changed = true
		}
	}
	if !changed {
		return nil
	}
	devbox["env"] = current
	out, err := json.MarshalIndent(devbox, "", "  ")
	if err != nil {
		return err
	}
	return fsutil.AtomicWrite(path, out, 0644)
}

// getDevboxPackages returns the devbox packages for a Frappe version
func getDevboxPackages(version string) []string {
	// Base packages
	packages := []string{
		"uv",
		"python@3.11",
		"nodejs@18",
		"yarn",
		"mariadb@10.11",
		"redis@7",
		"process-compose",
	}

	// Add version-specific packages. Derived from the compatibility table so
	// branch targets (e.g. develop) map to a real runtime instead of silently
	// falling back to the v15 defaults.
	fv, err := tools.GetFrappeVersion(tools.NormalizeFrappeVersion(version))
	if err != nil {
		return packages
	}

	pythonPkg := fmt.Sprintf("python@%s", fv.PythonVersion)
	if !strings.Contains(strings.Join(packages, " "), pythonPkg) {
		packages = append(packages, pythonPkg)
	}
	nodePkg := fmt.Sprintf("nodejs@%s", fv.NodeVersion)
	if !strings.Contains(strings.Join(packages, " "), nodePkg) {
		packages = append(packages, nodePkg)
	}
	if fv.PackageManager != "yarn" {
		packages = append(packages, fv.PackageManager)
	}

	return packages
}
